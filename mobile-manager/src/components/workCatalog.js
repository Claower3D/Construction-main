const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е').trim();

// Плоский список: [{ name, group, groupId, icon, hay }]
export const WORK_ITEMS = WORK_GROUPS.flatMap((g) =>
  g.items.map((it) => ({ name: it.name, group: g.name, groupId: g.id, icon: g.icon, hay: norm(`${it.name} ${it.keys || ''} ${g.name}`) })),
);

// Поиск: каждое слово запроса должно встретиться в названии, подсказках или группе. Сначала — совпадения в названии.
export function searchWorks(query, limit = 40) {
  const words = norm(query).split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const found = WORK_ITEMS.filter((it) => words.every((w) => it.hay.includes(w)));
  const inName = (it) => (words.every((w) => norm(it.name).includes(w)) ? 0 : 1);
  return found.sort((a, b) => inName(a) - inName(b)).slice(0, limit);
}

export function findWork(name) {
  const n = norm(name);
  return WORK_ITEMS.find((it) => norm(it.name) === n) || null;
}

// Группа для произвольного названия (голосовой ввод, старые заявки): ищем самое похожее.
export function groupOfWork(name) {
  const exact = findWork(name);
  if (exact) return exact.group;
  const first = searchWorks(String(name || '').split(/[\s,(]+/).slice(0, 2).join(' '), 1)[0];
  return first ? first.group : '';
}
