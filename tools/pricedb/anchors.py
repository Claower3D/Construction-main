"""Опорные цены (Алматы, 2026, ₸) для проверки прайс-базы QazGost.

Это не прайс-лист, а «коридоры здравого смысла»: позиция считается правдоподобной,
если её цена лежит в пределах [typical / TOL, typical * TOL]. Ориентиры собраны по
открытым объявлениям и прайсам поставщиков РК (OLX/Kaspi/Satu, 2026) и типовым
расценкам бригад; их задача — ловить ошибки масштаба (×5…×20), а не спорить о 10 %.

Каждый якорь: (regex по названию, набор единиц, функция/число типовой цены).
Функция получает (name_lower, match) и может пересчитать цену из размеров в названии.
"""
import re

TOL = 2.5


def _dims_mm(name):
    m = re.search(r'(\d{2,4})\s*[x×х*]\s*(\d{2,4})\s*[x×х*]\s*(\d{2,4})', name)
    if not m:
        return None
    a, b, c = (int(x) for x in m.groups())
    return a * b * c / 1e9  # м³


def _block_piece(per_m3, default_m3):
    def f(name, _m):
        v = _dims_mm(name) or default_m3
        return per_m3 * v
    return f


def _rebar_piece(name, _m):
    d = re.search(r'[øфd]\s*(\d{1,2})', name)
    length = re.search(r'\((\d{1,2}(?:[.,]\d)?)\s*м\)', name)
    if not d:
        return None
    dia = int(d.group(1))
    L = float(length.group(1).replace(',', '.')) if length else 1.0
    kg = 0.00617 * dia * dia * L
    return kg * 360  # ~360 000 ₸/т


def _rebar_meter(name, _m):
    d = re.search(r'[øфd]\s*(\d{1,2})', name)
    if not d:
        return None
    dia = int(d.group(1))
    return 0.00617 * dia * dia * 360


def _cable_meter(name, _m):
    m = re.search(r'(\d)\s*[x×х]\s*(\d{1,3}(?:[.,]\d)?)', name)
    if not m:
        return None
    cores, sec = int(m.group(1)), float(m.group(2).replace(',', '.'))
    return 50 + 65 * cores * sec


def _cable_coil(name, m):
    per_m = _cable_meter(name, m)
    if per_m is None:
        return None
    L = re.search(r'\((\d{2,3})\s*м\)', name)
    return per_m * (int(L.group(1)) if L else 100)


def _concrete(name, _m):
    g = re.search(r'м\s*-?\s*(\d{3})', name)
    if g:
        return 19000 + 30 * int(g.group(1))
    b = re.search(r'\bв\s*(\d{1,2}(?:[.,]\d)?)', name)
    if b:
        return 19000 + 30 * float(b.group(1).replace(',', '.')) * 13
    return 28000


def _pack_pieces(per_piece):
    def f(name, _m):
        n = re.search(r'\((\d{2,5})\s*шт\)', name)
        return per_piece * int(n.group(1)) if n else None
    return f


def _bag(per_kg):
    def f(name, _m):
        kg = re.search(r'(\d{1,2})\s*кг', name)
        return per_kg * int(kg.group(1)) if kg else None
    return f


