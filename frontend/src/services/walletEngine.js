// Одноразовая очистка демо-кошельков прошлых версий: фейковые балансы, операции и «привязанные» карты
function purgeLegacyDemoWallet() {
  try {
    if (typeof localStorage === 'undefined') return;
    for (let i = localStorage.length - 1; i >= 0; i -= 1) {
      const k = localStorage.key(i);
      if (k && (k.startsWith('qazgost_balance_') || k.startsWith('qazgost_transactions_') || k.startsWith('qazgost_cards_') || k.startsWith('qazgost_plan_'))) {
        localStorage.removeItem(k);
      }
    }
  } catch (e) { /* хранилище недоступно — нечего чистить */ }
}
purgeLegacyDemoWallet();

/** Сумма > 0 в тенге (число) или NaN. Строки «5 000» / «5000,5» допускаются. */
export function toAmountKZT(value) {
  const n = typeof value === 'number'
    ? value
    : Number(String(value ?? '').replace(/[\s  ]/g, '').replace(',', '.'));
  return Number.isFinite(n) && n > 0 ? Math.round(n) : NaN;
}

