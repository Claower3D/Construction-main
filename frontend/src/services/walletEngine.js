/** Подпись способа оплаты для заявки, оформленной без предоплаты. */
export function noPrepaymentLabel(method) {
  if (method === 'invoice') return 'Безналичный расчёт по счёту — без предоплаты через платформу';
  return 'Оплата напрямую исполнителю — без предоплаты через платформу';
}
